#!/usr/bin/env python3
"""Render protocol/reference/wire-tables.md from the generated wire-v1 contract.

Inputs (never edited by this script): protocol/v1/method-matrix.json, the JSON Schemas under
protocol/v1/schemas/ and the runtime golden protocol/v1/conformance/golden.json. Parameter tables
come from the schemas (with the Rust defaults recorded in ``x-rust-defaults``); result-member
tables come from the golden's observed success cases (member name -> JSON kind). Nothing is typed
by hand, so the page cannot drift from the contract.

    python3 scripts/docs/generate-wire-tables.py           # rewrite the page
    python3 scripts/docs/generate-wire-tables.py --check   # exit 1 if the page is stale
"""
from __future__ import annotations

import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
V1 = ROOT / "protocol" / "v1"
OUTPUT = ROOT / "protocol" / "reference" / "wire-tables.md"

DEFAULT_TEXT = {"yes()": "true", "two()": "2", "rgba()": '"RGBA8"',
                "start()": '"start"', "nearest()": '"nearest"', "children_limit()": "256", "query_limit()": "1024",
                "mouse_pointer()": "1", "no_direction()": '"none"', "preserve_selection()": '"preserve"',
                "default_width()": "900", "default_height()": "560", "patch_value": "unchanged"}


def type_of(schema: dict, defs: dict) -> str:
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return name
    if "anyOf" in schema:
        kinds: list[str] = []
        for part in schema["anyOf"]:
            for kind in type_of(part, defs).split(" or "):
                if kind not in kinds:
                    kinds.append(kind)
        return " or ".join(kinds)
    if schema.get("type") == "array":
        return f"array of {type_of(schema.get('items', {}), defs)}"
    kind = schema.get("type", "any")
    if schema.get("minimum") == 0 and kind == "integer":
        kind += " ≥0"
    return kind


def param_rows(schema: dict, defs: dict) -> list[str]:
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    defaults = schema.get("x-rust-defaults", {})
    rows = []
    for name, prop in props.items():
        if name == "op":
            continue
        if name in required:
            note = "required"
        elif name in defaults:
            default = defaults[name]
            if default == "Default::default()":
                kind = type_of(prop, defs)
                default_text = ("null" if "null" in kind else "0" if kind.startswith("integer")
                                else "false" if kind == "boolean" else '""' if kind == "string"
                                else "[]" if kind.startswith("array") else "empty")
            else:
                default_text = DEFAULT_TEXT.get(default, f"`{default}`")
            note = "optional, default " + default_text
        else:
            note = "optional"
        rows.append(f"`{name}`: {type_of(prop, defs).replace('|', '/')} ({note})")
    return rows


def golden_results(cases: dict, prefix: str) -> str:
    """Union of top-level result members observed in successful golden cases with this prefix."""
    members: dict[str, list[str]] = {}
    array = None
    for key, value in cases.items():
        if not key.startswith(prefix) or ".prelude." in key or not isinstance(value, dict):
            continue
        if value.get("ok") == "object":
            for name, kind in value.get("members", {}).items():
                kinds = members.setdefault(name, [])
                if kind not in kinds:
                    kinds.append(kind)
        elif value.get("ok") == "array":
            array = "array"
    if members:
        return ", ".join(f"`{n}` {'/'.join(sorted(k))}" for n, k in sorted(members.items()))
    return array or "—"


def golden_errors(cases: dict, prefix: str) -> str:
    out = []
    for key, value in sorted(cases.items()):
        if key.startswith(prefix) and ".prelude." not in key and isinstance(value, dict) and "error" in value:
            out.append(f"{key[len(prefix):]} → {value['error']}")
    return "; ".join(out) or "—"


def render() -> str:
    matrix = json.loads((V1 / "method-matrix.json").read_text(encoding="utf-8"))
    golden = json.loads((V1 / "conformance" / "golden.json").read_text(encoding="utf-8"))
    command = json.loads((V1 / "schemas" / "document-command.schema.json").read_text(encoding="utf-8"))
    cases, defs = golden["cases"], command["$defs"]
    lines = [
        "<!-- GENERATED by scripts/docs/generate-wire-tables.py from protocol/v1/. Do not edit. -->",
        "# Wire v1 tables (generated)",
        "",
        "Parameters come from the JSON Schemas in [`../v1/schemas/`](../v1/schemas/) (generated from the Rust "
        "serde types); *result members* and *golden errors* come from the runtime golden "
        f"[`../v1/conformance/golden.json`](../v1/conformance/golden.json) ({len(cases)} cases, host "
        f"{golden['host_version']}, {golden['mode']}). The golden records the JSON kind of each top-level "
        "member of the results it observed; members that only appear in other situations (or on a native "
        "desktop) are not listed. The schemas and the golden are the source of truth; the "
        "[protocol reference](../README.md) explains semantics.",
        "",
        "Regenerate with `python3 scripts/docs/generate-wire-tables.py` (`--check` verifies).",
        "",
        "## Client → host methods",
        "",
        "| Method | Params | Result members (golden) | Golden errors |",
        "|---|---|---|---|",
    ]
    for name, entry in matrix["methods"].items():
        if entry["direction"] != "client->host":
            continue
        params = entry["params"]
        if params.get("schema"):
            schema = json.loads((V1 / params["schema"]).read_text(encoding="utf-8"))
            if name == "document.command":
                text = "`window_id`, `document_id`, `command` (one op object, see below)"
            else:
                text = "<br>".join(param_rows(schema, schema.get("$defs", {}))) or "none"
            if params.get("decoded") == "manual":
                text += "<br>" + params["note"]
        else:
            text = "params not decoded (any object or omitted)"
        lines.append(f"| `{name}` | {text} | {golden_results(cases, name + '.')} | {golden_errors(cases, name + '.')} |")
    secondary = [(n, e) for n, e in matrix["methods"].items() if e["direction"] == "secondary-launcher->host"]
    lines += ["", "## Secondary launcher → host", "", "| Method | Params |", "|---|---|"]
    lines += [f"| `{n}` | {e['params']['note']} |" for n, e in secondary]
    lines += ["", "## Host → client messages", "", "| Method | Kind | Params | Reply |", "|---|---|---|---|"]
    for name, entry in matrix["methods"].items():
        if entry["direction"] != "host->client":
            continue
        params = ", ".join(f"`{p}`" if not p.startswith("<") else p.replace("<", "&lt;").replace(">", "&gt;")
                           for p in entry["params"])
        reply = ", ".join(f"`{k}`: {v}" for k, v in entry.get("reply", {}).items()) or "—"
        lines.append(f"| `{name}` | {entry['kind']} | {params} | {reply} |")
    lines += ["", f"## `document.command` ops ({len(matrix['document_command_ops'])})", "",
              "`element` is an HTML `id`; `node` is an opaque generation-checked node reference "
              "(`node:…`) returned by ops such as `query_nodes` and `node_of`.", "",
              "| Op | Fields | Result members (golden) | Golden errors |", "|---|---|---|---|"]
    for op in matrix["document_command_ops"]:
        schema = defs[f"op_{op}"]
        fields = "<br>".join(param_rows(schema, defs)) or "none"
        if "x-unknown-members" in schema:
            fields += " (unknown members ignored)"
        prefix = f"op.{op}."
        lines.append(f"| `{op}` | {fields} | {golden_results(cases, prefix)} | {golden_errors(cases, prefix)} |")
    for name in ("BatchOp", "NodeBatchOp"):
        lines += ["", f"### `{name}` (items of `{'batch' if name == 'BatchOp' else 'node_batch'}`.`ops`)", "",
                  "| op | Fields |", "|---|---|"]
        for variant in defs[name]["oneOf"]:
            lines.append(f"| `{variant['properties']['op']['const']}` | {'<br>'.join(param_rows(variant, defs))} |")
    lines += ["", "### `ResourceEntry` (items of `register_resource_bundle`.`entries`)", "",
              "| Fields |", "|---|", "| " + "<br>".join(param_rows(defs["ResourceEntry"], defs)) + " |"]
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True)))
            print("STALE: protocol/reference/wire-tables.md", file=sys.stderr)
            return 1
        print("OK: protocol/reference/wire-tables.md matches protocol/v1/")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
